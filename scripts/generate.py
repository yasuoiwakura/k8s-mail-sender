#!/usr/bin/env python3
"""Generate Kubernetes ConfigMaps from config/domains.yaml.

KISS: no external dependencies. The YAML subset used by domains.yaml is
parsed with a few simple rules so this works on Linux, macOS and Windows.

Usage:
    python scripts/generate.py
    python scripts/generate.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config" / "domains.yaml"
ENV_OUT = ROOT / "manifests" / "10-configmap-env.yaml"
FILES_OUT = ROOT / "manifests" / "11-configmap-files.yaml"

DOMAIN_RE = re.compile(r"^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$")


def parse_config(text: str) -> tuple[list[str], dict[str, str]]:
    domains: list[str] = []
    settings: dict[str, str] = {}
    section = ""

    for raw_line in text.splitlines():
        line = raw_line.split("#", 1)[0].rstrip()
        if not line.strip():
            continue

        stripped = line.strip()
        if stripped == "domains:":
            section = "domains"
            continue
        if stripped == "mail:":
            section = "mail"
            continue

        if section == "domains":
            match = re.match(r"^\s*-\s*(\S+)\s*$", line)
            if match:
                domains.append(match.group(1))
        elif section == "mail":
            match = re.match(r"^\s*([a-z_]+):\s*(.*?)\s*$", line)
            if match:
                settings[match.group(1)] = match.group(2).strip("\"'")

    if not domains:
        raise ValueError("no domains found in config/domains.yaml")

    for domain in domains:
        if not DOMAIN_RE.match(domain):
            raise ValueError(f"invalid domain: {domain!r}")

    required = {
        "hostname",
        "auth_account",
        "dkim_selector",
        "bounce_address",
        "postmaster_address",
        "inet_protocols",
    }
    missing = required - settings.keys()
    if missing:
        raise ValueError(f"missing mail settings: {', '.join(sorted(missing))}")

    return domains, settings


def pcre_escape(value: str) -> str:
    # Escape PCRE metacharacters, but leave '-' and '@' readable.
    return re.sub(r"([\\.^$|?*+()\[\]{}])", r"\\\1", value)


def configmap_header(name: str) -> str:
    return (
        "# Generated by scripts/generate.py from config/domains.yaml.\n"
        "# Do not edit manually; change config/domains.yaml and regenerate.\n"
        "apiVersion: v1\n"
        "kind: ConfigMap\n"
        "metadata:\n"
        f"  name: {name}\n"
        "  namespace: mail\n"
        "data:\n"
    )


def block_scalar(key: str, content: str) -> str:
    lines = [f"  {key}: |"]
    for line in content.rstrip("\n").splitlines():
        lines.append(f"    {line}" if line else "")
    return "\n".join(lines) + "\n"


def build_env(settings: dict[str, str]) -> str:
    values = {
        "ACCOUNT_PROVISIONER": "FILE",
        "OVERRIDE_HOSTNAME": settings["hostname"],
        "POSTMASTER_ADDRESS": settings["postmaster_address"],
        "LOG_LEVEL": "info",
        "TZ": "Europe/Berlin",
        "PERMIT_DOCKER": "none",
        "SPOOF_PROTECTION": "0",
        "ENABLE_IMAP": "0",
        "ENABLE_POP3": "0",
        "ENABLE_SASLAUTHD": "0",
        "ENABLE_OPENDKIM": "1",
        "ENABLE_OPENDMARC": "0",
        "ENABLE_POLICYD_SPF": "0",
        "ENABLE_RSPAMD": "0",
        "ENABLE_AMAVIS": "0",
        "ENABLE_CLAMAV": "0",
        "ENABLE_SPAMASSASSIN": "0",
        "ENABLE_POSTGREY": "0",
        "ENABLE_FAIL2BAN": "0",
        "ENABLE_DNSBL": "0",
        "ENABLE_SRS": "0",
        "ENABLE_UPDATE_CHECK": "0",
        "ENABLE_QUOTAS": "0",
        "ENABLE_FETCHMAIL": "0",
        "ENABLE_GETMAIL": "0",
        "ENABLE_MTA_STS": "0",
        "POSTFIX_REJECT_UNKNOWN_CLIENT_HOSTNAME": "0",
        "POSTFIX_MESSAGE_SIZE_LIMIT": "26214400",
        "POSTFIX_INET_PROTOCOLS": settings["inet_protocols"],
        "DOVECOT_INET_PROTOCOLS": settings["inet_protocols"],
        "TLS_LEVEL": "modern",
        "SSL_TYPE": "manual",
        "SSL_CERT_PATH": "/secrets/tls/tls.crt",
        "SSL_KEY_PATH": "/secrets/tls/tls.key",
    }

    lines = [configmap_header("dms-env").rstrip("\n")]
    for key, value in values.items():
        lines.append(f'  {key}: "{value}"')
    return "\n".join(lines) + "\n"


def build_files(domains: list[str], settings: dict[str, str]) -> str:
    sender_domains = "\n".join(f"{domain} OK" for domain in domains) + "\n<> OK\n"

    domain_pattern = "|".join(pcre_escape(domain) for domain in domains)
    from_domains = (
        "if /^From:/\n"
        f"!/^From:.*@(?:{domain_pattern})[ \\t]*>?[ \\t]*$/i "
        "REJECT 5.7.1 Sender domain not allowed\n"
        "endif\n"
    )

    bounce_address = settings["bounce_address"]
    sender_canonical = (
        f"/^(?!{pcre_escape(bounce_address)}$).+@.+/i {bounce_address}\n"
    )

    postfix_main = (
        "# Envelope sender domain allowlist.\n"
        "dms_smtpd_sender_restrictions = "
        "check_sender_access texthash:/tmp/docker-mailserver/sender_domains, reject\n"
        "\n"
        "# Rewrite the envelope sender to a reachable bounce address.\n"
        "sender_canonical_maps = "
        "pcre:/tmp/docker-mailserver/sender_canonical.pcre\n"
        "sender_canonical_classes = envelope_sender\n"
    )

    postfix_master = (
        "# Apply the From: header check on the submission ports without\n"
        "# losing the DMS privacy header filter.\n"
        "sender-cleanup/unix/header_checks="
        "pcre:/etc/postfix/maps/sender_header_filter.pcre, "
        "pcre:/tmp/docker-mailserver/from_domains.pcre\n"
    )

    files = {
        "postfix-main.cf": postfix_main,
        "postfix-master.cf": postfix_master,
        "sender_domains": sender_domains,
        "from_domains.pcre": from_domains,
        "sender_canonical.pcre": sender_canonical,
        "domains.txt": "\n".join(domains) + "\n",
    }

    output = [configmap_header("dms-files").rstrip("\n")]
    for key, content in files.items():
        output.append(block_scalar(key, content).rstrip("\n"))
    return "\n".join(output) + "\n"


def write_or_check(path: Path, content: str, check: bool) -> bool:
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
            return False
        return True

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    domains, settings = parse_config(CONFIG.read_text(encoding="utf-8"))
    env_yaml = build_env(settings)
    files_yaml = build_files(domains, settings)

    ok = True
    ok = write_or_check(ENV_OUT, env_yaml, args.check) and ok
    ok = write_or_check(FILES_OUT, files_yaml, args.check) and ok

    if not ok:
        print("generated files are stale; run python scripts/generate.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
